// Cloudflare Worker specific utilities and examples
export interface WorkerContext {
  request: {
    url: string;
    method: string;
    headers: Record<string, string>;
  };
  env?: Record<string, any>;
  timestamp: string;
}

export interface WorkerResponse {
  status: number;
  headers: Record<string, string>;
  body: string | object;
  processing: {
    duration: number;
    timestamp: string;
    source: string;
  };
}

// Parse request information
export function parseWorkerRequest(url: string, method: string = 'GET'): {
  pathname: string;
  searchParams: Record<string, string>;
  segments: string[];
} {
  const urlObj = new URL(url);
  const searchParams: Record<string, string> = {};
  
  // Parse search params
  urlObj.searchParams.forEach((value, key) => {
    searchParams[key] = value;
  });

  return {
    pathname: urlObj.pathname,
    searchParams,
    segments: urlObj.pathname.split('/').filter(Boolean)
  };
}

// Generate worker-style responses
export function createWorkerResponse(
  data: any,
  status: number = 200,
  headers: Record<string, string> = {}
): WorkerResponse {
  const defaultHeaders = {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Cache-Control': 'public, max-age=300'
  };

  return {
    status,
    headers: { ...defaultHeaders, ...headers },
    body: typeof data === 'string' ? data : JSON.stringify(data, null, 2),
    processing: {
      duration: Math.random() * 100 + 10, // Simulated processing time
      timestamp: new Date().toISOString(),
      source: 'Module Federation Worker Utils'
    }
  };
}

// Handle different HTTP methods
export function handleRequest(method: string, path: string, data?: any): WorkerResponse {
  const startTime = Date.now();
  
  switch (method.toUpperCase()) {
    case 'GET':
      return createWorkerResponse({
        message: `GET request to ${path}`,
        data: { path, timestamp: new Date().toISOString() }
      });
    
    case 'POST':
      return createWorkerResponse({
        message: `POST request to ${path}`,
        received: data,
        processed: true,
        id: Math.random().toString(36).substring(7)
      }, 201);
    
    case 'PUT':
      return createWorkerResponse({
        message: `PUT request to ${path}`,
        updated: data,
        success: true
      });
    
    case 'DELETE':
      return createWorkerResponse({
        message: `DELETE request to ${path}`,
        deleted: true,
        timestamp: new Date().toISOString()
      });
    
    default:
      return createWorkerResponse({
        error: `Method ${method} not supported`,
        supportedMethods: ['GET', 'POST', 'PUT', 'DELETE']
      }, 405);
  }
}

