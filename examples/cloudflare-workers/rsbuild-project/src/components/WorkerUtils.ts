// Simulate KV operations
export class MockKV {
  private store: Map<string, any> = new Map();

  async get(key: string): Promise<string | null> {
    return new Promise((resolve) => {
      setTimeout(() => {
        resolve(this.store.get(key) || null);
      }, Math.random() * 50 + 10); // 10-60ms delay
    });
  }

  async put(key: string, value: string): Promise<void> {
    return new Promise((resolve) => {
      setTimeout(() => {
        this.store.set(key, value);
        resolve();
      }, Math.random() * 30 + 5); // 5-35ms delay
    });
  }

  async delete(key: string): Promise<void> {
    return new Promise((resolve) => {
      setTimeout(() => {
        this.store.delete(key);
        resolve();
      }, Math.random() * 20 + 5); // 5-25ms delay
    });
  }

  async list(): Promise<string[]> {
    return new Promise((resolve) => {
      setTimeout(() => {
        resolve(Array.from(this.store.keys()));
      }, Math.random() * 40 + 10); // 10-50ms delay
    });
  }
}

// Demo function for worker capabilities
export async function demonstrateWorkerCapabilities(): Promise<any> {
  const kv = new MockKV();
  
  // KV operations
  await kv.put('user:1', JSON.stringify({ name: 'Alice', role: 'admin' }));
  await kv.put('config:app', JSON.stringify({ version: '1.0.0', debug: false }));
  
  const userData = await kv.get('user:1');
  const configData = await kv.get('config:app');
  const allKeys = await kv.list();

  // Request handling
  const getResponse = handleRequest('GET', '/api/users');
  const postResponse = handleRequest('POST', '/api/users', { name: 'David', role: 'user' });

  // Route handling
  const homeRoute = routeHandler('/');
  const healthRoute = routeHandler('/health');

  return {
    demo: 'worker-capabilities',
    timestamp: new Date().toISOString(),
    kv: {
      operations: ['put', 'get', 'list'],
      userData: userData ? JSON.parse(userData) : null,
      configData: configData ? JSON.parse(configData) : null,
      allKeys
    },
    requests: {
      get: getResponse,
      post: postResponse
    },
    routes: {
      home: homeRoute,
      health: healthRoute
    },
    summary: {
      kvOperations: 3,
      requestsHandled: 2,
      routesTested: 2,
      processing: 'successful'
    }
  };
}

